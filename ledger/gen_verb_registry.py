"""Generate the ledger's static verb registry from its verbs directory.

``ledger/verbs/_registry.py`` imports every verb module by name so that the
``--linear`` install check, which follows static imports only, reads every
verb the ledger CLI can load. This module writes that file from the directory
itself: one entry for every ``*.py`` file in ``ledger/verbs/`` that is not
``__init__.py`` and does not start with ``_``, sorted by file name. A symlink
is refused by name, before any other test. Never edit the registry by hand;
add or remove a verb module, then rerun this module. Run it from the folder
that holds ``ledger/``:

    python3 -m ledger.gen_verb_registry          # write it
    python3 -m ledger.gen_verb_registry --check  # compare only

``--check`` writes nothing. It exits 0 when the registry on disk is exactly
what this module would write, and otherwise exits 1 and prints the command
that regenerates it.

Exit 2, writing nothing, when the verbs directory is missing or cannot be
listed, holds a symlink, holds no verb module, holds a ``.py`` entry that is
not a regular file, or names a module that is not a valid Python identifier;
or when the registry cannot be read or written. The module never writes an
empty registry.
"""
from __future__ import annotations

import argparse
import keyword
import sys
from pathlib import Path

VERBS_DIR = Path(__file__).resolve().parent / "verbs"
REGISTRY = VERBS_DIR / "_registry.py"
REGISTRY_NAME = "ledger/verbs/_registry.py"
COMMAND = "python3 -m ledger.gen_verb_registry"

EXIT_OK = 0
EXIT_STALE = 1
EXIT_REFUSED = 2

HEADER = f'''"""The ledger's verb modules, listed statically.

Generated by ``{COMMAND}`` from the
verb modules in this directory. Never edit this file by hand: add or remove a
verb module beside it, then rerun that command. CI runs the command with
``--check`` and fails when this file and the directory disagree.

``discover_verbs`` loads exactly these modules, in this order (sorted by file
name). The list is static so that the ``--linear`` install check, which
follows static imports only, reads every verb the CLI can load.
"""
from __future__ import annotations

'''


class RegistryError(Exception):
    """The registry cannot be generated or compared; nothing is written."""


def verb_modules(verbs_dir: Path) -> list[str]:
    """Return the verb module names in ``verbs_dir``, sorted by file name."""
    try:
        entries = sorted(verbs_dir.iterdir(), key=lambda entry: entry.name)
    except OSError as exc:
        raise RegistryError(f"cannot list the verbs directory {verbs_dir}: {exc}") from exc
    modules: list[str] = []
    for entry in entries:
        if entry.is_symlink():
            raise RegistryError(f"verb entry is a symlink: {entry}")
        name = entry.name
        if not name.endswith(".py") or name == "__init__.py" or name.startswith("_"):
            continue
        if not entry.is_file():
            raise RegistryError(f"verb entry is not a regular file: {entry}")
        module = name[: -len(".py")]
        if not module.isidentifier() or keyword.iskeyword(module):
            raise RegistryError(
                f"verb module name is not a valid Python identifier: {name}"
            )
        modules.append(module)
    if not modules:
        raise RegistryError(f"the verbs directory holds no verb module: {verbs_dir}")
    return modules


def render(modules: list[str]) -> str:
    """Return the registry source for ``modules``, in the order given."""
    imports = "".join(f"from ledger.verbs import {name}\n" for name in modules)
    entries = "".join(f"    {name},\n" for name in modules)
    return f"{HEADER}{imports}\nMODULES = (\n{entries})\n"


def check(expected: bytes, count: int) -> int:
    try:
        current = REGISTRY.read_bytes()
    except FileNotFoundError:
        current = None
    except OSError as exc:
        raise RegistryError(f"cannot read {REGISTRY}: {exc}") from exc
    if current == expected:
        print(f"{REGISTRY_NAME} is current ({count} verb modules)")
        return EXIT_OK
    print(
        f"{REGISTRY_NAME} does not match the verbs directory. Regenerate it, "
        "from the folder that holds ledger/, with:\n"
        f"  {COMMAND}",
        file=sys.stderr,
    )
    return EXIT_STALE


def write(expected: bytes, count: int) -> int:
    try:
        REGISTRY.write_bytes(expected)
    except OSError as exc:
        raise RegistryError(f"cannot write {REGISTRY}: {exc}") from exc
    print(f"wrote {REGISTRY_NAME} ({count} verb modules)")
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python3 -m ledger.gen_verb_registry",
        description="Generate the ledger's static verb registry from its verbs directory.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when the registry on disk differs from what "
        "this module would write",
    )
    args = parser.parse_args(argv)
    try:
        modules = verb_modules(VERBS_DIR)
        expected = render(modules).encode("utf-8")
        if args.check:
            return check(expected, len(modules))
        return write(expected, len(modules))
    except RegistryError as exc:
        print(f"gen_verb_registry: {exc}", file=sys.stderr)
        return EXIT_REFUSED


if __name__ == "__main__":
    raise SystemExit(main())
